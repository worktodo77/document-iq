"""Acceptance criterion 4 — Bates detection accuracy, by D-23's method.

    python tools/bates_acceptance.py --corpus "<MNFV root>" [--sample-pages N]
    python tools/bates_acceptance.py --negative-control "<Petrobras root>"

D-23 rules the method: a **sequence-continuity proof over the whole set**, which
catches the systematic error class a sample cannot see, plus a **hand-checked
stratified sample** for absolute correctness. It also records an assumption that
turned out not to hold, and the correction matters more than the tool:

**D-23 assumed every ground-truth number would itself be OCR of a footer stamp.**
It is not. The MNFV disclosure is a standard e-discovery production and ships its
own **load files** — ``.OPT`` (Opticon: one line per page, page-level Bates and
document breaks), ``.LFP``, ``.DAT`` (document-level Begin/End Bates) and
``.LST``. Those are the *producing party's* authoritative numbering, generated by
the production vendor at the moment the stamps were burned in, and they are not
derived from reading the stamps back. So page-level ground truth for the
2,138-document production is **authoritative, not OCR-derived**, and the accuracy
figure is a comparison against it rather than against a second reading of the
same footer.

The second half of the set — the 17 combined PDFs under ``Initial Disclosures``
and ``Supplemental`` — has **no load file**. Its ground truth is document-level
only, carried in the filenames, and D-23's caveat applies there in full.

Both are measured and both are reported separately. Collapsing them into one
percentage would be the more flattering number and the less honest one.

NOTHING HERE WRITES INSIDE THE REPOSITORY. The corpus is client material; the
report goes wherever ``--out`` points and the caller is expected to keep that
outside the working tree.
"""

