# (a) the continuity proof — the whole set, the systematic error class
# ---------------------------------------------------------------------------


@dataclass
class ContinuityReport:
    label: str
    documents: int = 0
    pages: int = 0
    findings: list[str] = field(default_factory=list)
    checks: list[str] = field(default_factory=list)

    @property
    def ok(self) -> bool:
        return not self.findings

    def render(self) -> str:
        head = (f"[{self.label}] {self.documents} document(s), {self.pages} "
                f"page(s) — {'CONTINUOUS' if self.ok else str(len(self.findings)) + ' FINDING(S)'}")
        return "\n".join([head] + [f"    check   {c}" for c in self.checks]
                         + [f"    FINDING {f}" for f in self.findings])


def continuity_from_opt(pages: list[OptPage], label: str) -> ContinuityReport:
    """Monotonic, gapless, non-overlapping, contiguous — over every page.

    Each property is checked separately and reported separately, because they
    fail for different reasons: a gap is a dropped page, an overlap is a
    document-boundary error, and a non-monotonic step is a numbering error. A
    single "continuous / not continuous" verdict would name none of them.
    """
    rep = ContinuityReport(label)
    parsed = [(p, split_bates(p.bates)) for p in pages]
    unparsed = [p.bates for p, s in parsed if s is None]
    if unparsed:
        rep.findings.append(f"{len(unparsed)} page number(s) do not parse as "
                            f"<prefix><digits>, e.g. {unparsed[:3]}")
    good = [(p, s) for p, s in parsed if s is not None]
    rep.pages = len(good)
    if not good:
        rep.findings.append("no parseable page numbers at all")
        return rep

    prefixes = Counter(s[0] for _, s in good)
    rep.checks.append(f"one prefix across the production: "
                      f"{dict(prefixes)}" if len(prefixes) > 1 else
                      f"single prefix {next(iter(prefixes))!r}")
    if len(prefixes) > 1:
        rep.findings.append(f"{len(prefixes)} distinct prefixes: {dict(prefixes)}")

    widths = Counter(s[2] for _, s in good)
    rep.checks.append(f"digit widths present: {dict(sorted(widths.items()))}")

    numbers = [s[1] for _, s in good]
    non_mono = [i for i in range(1, len(numbers)) if numbers[i] <= numbers[i - 1]]
    rep.checks.append(f"strictly increasing in file order: "
                      f"{'yes' if not non_mono else str(len(non_mono)) + ' step(s) not'}")
    if non_mono:
        rep.findings.append(
            f"{len(non_mono)} page(s) do not increase over the previous page, "
            f"first at index {non_mono[0]}")

    gaps = [(numbers[i - 1], numbers[i])
            for i in range(1, len(numbers)) if numbers[i] != numbers[i - 1] + 1]
    rep.checks.append(f"contiguous across the whole production: "
                      f"{'yes' if not gaps else str(len(gaps)) + ' break(s)'}")
    if gaps:
        rep.findings.append(
            f"{len(gaps)} break(s) in the production sequence, first "
            f"{gaps[0][0]} -> {gaps[0][1]}"
            + (f" (total {sum(b - a - 1 for a, b in gaps)} number(s) unaccounted)"))

    # Per-document: a document's own pages must be a contiguous run.
    docs: list[list[int]] = []
    for p, s in good:
        if p.doc_break or not docs:
            docs.append([])
        docs[-1].append(s[1])
    rep.documents = len(docs)
    ragged = [d for d in docs if d != list(range(d[0], d[0] + len(d)))]
    rep.checks.append(f"every document's own pages are a gapless run: "
                      f"{'yes' if not ragged else str(len(ragged)) + ' ragged'}")
    if ragged:
        rep.findings.append(f"{len(ragged)} document(s) have a gap or a "
                            f"repeat inside their own Bates range")

    spans = [(d[0], d[-1]) for d in docs]
    overlaps = [(spans[i - 1], spans[i])
                for i in range(1, len(spans)) if spans[i][0] <= spans[i - 1][1]]
    rep.checks.append(f"document ranges do not overlap: "
                      f"{'yes' if not overlaps else str(len(overlaps)) + ' overlap(s)'}")
    if overlaps:
        rep.findings.append(f"{len(overlaps)} overlapping document range(s), "
                            f"first {overlaps[0]}")
    return rep


def continuity_from_filenames(ranges: list[NamedRange],
                              page_counts: dict[Path, int],
                              label: str) -> ContinuityReport:
    """The same properties, for the set whose only ground truth is its names.

    Weaker on purpose and labelled as such: a filename range is what the
    producing party *called* the file, and the page count is what the PDF
    actually holds. Where they disagree the disagreement is the finding.
    """
    rep = ContinuityReport(label)
    rep.documents = len(ranges)
    ordered = sorted(ranges, key=lambda r: (r.prefix, r.start))
    rep.pages = sum(page_counts.get(r.path, 0) for r in ordered)

    widths = Counter(r.width for r in ordered)
    rep.checks.append(f"digit widths in the names: {dict(sorted(widths.items()))}")

    mismatched = [(r, page_counts.get(r.path), r.end - r.start + 1)
                  for r in ordered
                  if page_counts.get(r.path) is not None
                  and page_counts[r.path] != r.end - r.start + 1]
    rep.checks.append(f"named range length equals the PDF's page count: "
                      f"{'yes' if not mismatched else str(len(mismatched)) + ' mismatch(es)'}")
    for r, actual, named in mismatched:
        rep.findings.append(
            f"{r.prefix} {r.start}-{r.end} names {named} page(s) but the PDF "
            f"holds {actual}")

    for i in range(1, len(ordered)):
        a, b = ordered[i - 1], ordered[i]
        if b.start <= a.end:
            rep.findings.append(
                f"overlapping named ranges: {a.prefix} {a.start}-{a.end} and "
                f"{b.prefix} {b.start}-{b.end}")
        elif b.start != a.end + 1:
            rep.findings.append(
                f"gap in the named sequence: {a.prefix} {a.end} -> "
                f"{b.prefix} {b.start} ({b.start - a.end - 1} number(s))")
    rep.checks.append(f"named ranges tile the production without gap or overlap: "
                      f"{'yes' if not rep.findings else 'no'}")
    return rep


