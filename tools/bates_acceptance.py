def _find_load_files(root: Path) -> list[Path]:
    return sorted(root.rglob("*.opt"), key=lambda p: str(p).lower()) or \
        sorted(root.rglob("*.OPT"), key=lambda p: str(p).lower())


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="bates_acceptance")
    ap.add_argument("--corpus", help="the stamped production root")
    ap.add_argument("--negative-control", help="an unstamped corpus root")
    ap.add_argument("--negative-limit", type=int, default=60)
    ap.add_argument("--sample-docs", type=int, default=120,
                    help="how many load-file documents to run DocIQ over. "
                         "The continuity proof always covers the WHOLE set; "
                         "this bounds only the page-level comparison, and the "
                         "bound is reported with what it left out.")
    ap.add_argument("--max-mb", type=float, default=60.0,
                    help="skip individual PDFs larger than this in the sampled "
                         "comparison. Disclosed, never silent: the skipped "
                         "files are listed in the report.")
    ap.add_argument("--seed", type=int, default=20240529)
    ap.add_argument("--no-footer-reocr", action="store_true",
                    help="run with D-25's targeted footer re-OCR disabled, to "
                         "produce the before-number with the after-code")
    ap.add_argument("--only-ocr-docs", action="store_true",
                    help="restrict the page-level comparison to sampled "
                         "documents that contain at least one page DocIQ must "
                         "OCR. The footer re-OCR cannot change any other "
                         "document, so this measures exactly the pages that "
                         "can move — at a fraction of the machine time. The "
                         "documents dropped are counted in the report.")
    ap.add_argument("--out", default="", help="write the JSON report here")
    args = ap.parse_args(argv)

    global FOOTER_REOCR
    FOOTER_REOCR = not args.no_footer_reocr

    reports: dict = {"generated": time.strftime("%Y-%m-%dT%H:%M:%S"),
                     "method": "D-23: whole-set continuity + sampled page-level "
                               "comparison against the production's load files"}

    if args.negative_control:
        rep = negative_control(Path(args.negative_control), args.negative_limit)
        print(rep.render())
        reports["negative_control"] = rep.__dict__ | {"accuracy_pct": rep.accuracy_pct}

    if args.corpus:
        root = Path(args.corpus)
        print(f"\n=== corpus: {root}\n")

        # --- (a) continuity, whole set, from the load files -----------------
        for opt in _find_load_files(root):
            pages = parse_opt(opt)
            rep = continuity_from_opt(pages, f"load file {opt.name}")
            print(rep.render() + "\n")
            reports.setdefault("continuity", []).append(
                {"label": rep.label, "documents": rep.documents,
                 "pages": rep.pages, "checks": rep.checks,
                 "findings": rep.findings})

        # --- (a') continuity for the combined PDFs, from their names --------
        named: list[NamedRange] = []
        for p in sorted(root.rglob("*.pdf")):
            if "images" in [q.lower() for q in p.parts]:
                continue
            r = parse_filename_range(p)
            if r is not None:
                named.append(r)
        if named:
            counts: dict[Path, int] = {}
            for r in named:
                try:
                    from pypdf import PdfReader

                    counts[r.path] = len(PdfReader(str(r.path)).pages)
                except Exception as exc:
                    print(f"    ! page count for {r.path.name}: {exc}")
            rep = continuity_from_filenames(named, counts,
                                            "combined PDFs (filename ranges)")
            print(rep.render() + "\n")
            reports.setdefault("continuity", []).append(
                {"label": rep.label, "documents": rep.documents,
                 "pages": rep.pages, "checks": rep.checks,
                 "findings": rep.findings})

        # --- (b) page-level accuracy against the authoritative load file ----
        for opt in _find_load_files(root):
            pages = parse_opt(opt)
            base = opt.parent.parent  # <production>/data/<x>.opt -> <production>
            by_image: dict[str, list[str]] = defaultdict(list)
            for pg in pages:
                by_image[pg.image_rel].append(pg.bates)
            candidates = []
            skipped_big: list[str] = []
            for rel, gt in sorted(by_image.items()):
                path = base / rel
                if not path.is_file():
                    continue
                mb = path.stat().st_size / (1024 * 1024)
                if mb > args.max_mb:
                    skipped_big.append(f"{rel} ({mb:.0f} MB, {len(gt)} pages)")
                    continue
                candidates.append((path, rel, gt))
            rng = random.Random(args.seed)
            rng.shuffle(candidates)
            chosen = sorted(candidates[:args.sample_docs], key=lambda t: t[1])
            dropped_native = 0
            if args.only_ocr_docs:
                keep = []
                for path, rel, gt in chosen:
                    got = has_ocr_pages(path)
                    if got is False:
                        dropped_native += 1
                        continue
                    keep.append((path, rel, gt))   # None (unreadable) is kept
                chosen = keep
            rep = measure_accuracy(chosen, f"page-level vs {opt.name}")
            rep.notes.append(f"footer re-OCR (D-25): "
                             f"{'ON' if FOOTER_REOCR else 'OFF'}")
            if args.only_ocr_docs:
                rep.notes.append(
                    f"--only-ocr-docs: {dropped_native} sampled document(s) "
                    f"have no page DocIQ must OCR and were not re-measured; "
                    f"the footer re-OCR cannot reach them")
            rep.notes.append(
                f"sampled {len(chosen)} of {len(candidates)} eligible "
                f"document(s) (seed {args.seed}); "
                f"{len(skipped_big)} document(s) skipped for exceeding "
                f"--max-mb {args.max_mb}")
            for s in skipped_big[:20]:
                rep.notes.append(f"skipped: {s}")
            print(rep.render() + "\n")
            reports.setdefault("accuracy", []).append(
                rep.__dict__ | {"accuracy_pct": rep.accuracy_pct})

    if args.out:
        Path(args.out).write_text(json.dumps(reports, indent=2, default=str),
                                  encoding="utf-8")
        print(f"\nreport written to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
