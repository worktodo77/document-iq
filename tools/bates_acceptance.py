_BATES_RE = re.compile(r"^(?P<prefix>[A-Za-z][A-Za-z0-9]*?)(?P<digits>\d+)$")


@dataclass(frozen=True, slots=True)
class OptPage:
    """One ``.OPT`` line: the Bates number of one page of one image file."""

    bates: str
    image_rel: str
    doc_break: bool


def parse_opt(path: Path) -> list[OptPage]:
    """Opticon: ``Bates,Volume,ImagePath,DocBreak,,,PageCount``.

    Read positionally rather than by header — the format has no header, and a
    reader that guessed columns by name would silently produce an empty ground
    truth, which compares equal to a perfect detection.
    """
    out: list[OptPage] = []
    with path.open("r", encoding="utf-8", errors="replace", newline="") as fh:
        for row in csv.reader(fh):
            if len(row) < 4 or not row[0].strip():
                continue
            out.append(OptPage(bates=row[0].strip(),
                               image_rel=row[2].strip().replace("\\", "/"),
                               doc_break=row[3].strip().upper() == "Y"))
    return out


def split_bates(s: str) -> tuple[str, int, int] | None:
    """``(prefix, number, digit width)`` — the parts continuity is judged on."""
    m = _BATES_RE.match(s.strip())
    if not m:
        return None
    d = m.group("digits")
    return m.group("prefix"), int(d), len(d)


# ---------------------------------------------------------------------------
# Ground truth 2 — the combined PDFs, whose range lives in the filename
# ---------------------------------------------------------------------------

# Filenames use both an ASCII hyphen and an EN DASH as the range separator, and
# both must be read: a parser that knew only "-" would read the en-dash file as
# unranged and quietly drop 332 pages of the production from the continuity
# proof — an absence that looks exactly like "this file is not stamped".
_FILENAME_RANGE_RE = re.compile(
    r"^(?P<prefix>[A-Z]{2,8})\s+(?P<start>\d{3,8})\s*(?:[-‐-―])\s*"
    r"(?P<end>\d{3,8})\b")
_FILENAME_SINGLE_RE = re.compile(r"^(?P<prefix>[A-Z]{2,8})\s+(?P<start>\d{3,8})\b")


@dataclass(frozen=True, slots=True)
class NamedRange:
    path: Path
    prefix: str
    start: int
    end: int
    width: int


def parse_filename_range(p: Path) -> NamedRange | None:
    m = _FILENAME_RANGE_RE.match(p.name)
    if m:
        return NamedRange(p, m.group("prefix"), int(m.group("start")),
                          int(m.group("end")), len(m.group("start")))
    m = _FILENAME_SINGLE_RE.match(p.name)
    if m:
        return NamedRange(p, m.group("prefix"), int(m.group("start")),
                          int(m.group("start")), len(m.group("start")))
    return None


